#!/usr/bin/env node
/**
 * Serpentine UserPromptSubmit hook — injects a compact codebase graph summary
 * into every Claude Code prompt so Claude has structural context without
 * needing to re-run analysis.
 *
 * Reads .claude/graph.json (written by serpentine after each analysis).
 * Skips silently if the file is missing, unreadable, or older than 10 minutes.
 * Never blocks the prompt — exits 0 on any error.
 */

import { readFileSync, statSync } from "node:fs";
import { resolve } from "node:path";

const GRAPH_PATH = resolve(".claude/graph.json");
const MAX_AGE_MS = 10 * 60 * 1000; // 10 minutes
const MAX_EDGES = 30;
const MAX_OUTPUT_BYTES = 2048;

function loadGraph() {
  const stat = statSync(GRAPH_PATH);
  if (Date.now() - stat.mtimeMs > MAX_AGE_MS) return null;
  return JSON.parse(readFileSync(GRAPH_PATH, "utf8"));
}

function flattenNodes(nodes, acc = []) {
  for (const node of nodes) {
    acc.push(node);
    if (node.children) flattenNodes(node.children, acc);
  }
  return acc;
}

function buildSummary(graph, promptText) {
  const allNodes = flattenNodes(graph.nodes ?? []);
  const localNodes = allNodes.filter((n) => (n.origin ?? "local") === "local");
  const localIds = new Set(localNodes.map((n) => n.id));

  // Top-level local modules
  const topModules = localNodes
    .filter((n) => !n.parent && (n.type ?? n.object_type) === "module")
    .map((n) => n.id);

  // Edges between local nodes, ranked by callee frequency
  const edges = (graph.edges ?? []).filter(
    (e) => localIds.has(e.caller) && localIds.has(e.callee)
  );
  const calleeFreq = {};
  for (const e of edges) calleeFreq[e.callee] = (calleeFreq[e.callee] ?? 0) + 1;
  const topEdges = [...edges]
    .sort((a, b) => (calleeFreq[b.callee] ?? 0) - (calleeFreq[a.callee] ?? 0))
    .slice(0, MAX_EDGES);

  // Expand neighbors of any node mentioned in the prompt
  const mentioned = localNodes.filter(
    (n) => promptText.includes(n.name) || promptText.includes(n.id)
  );
  const neighborEdges =
    mentioned.length > 0
      ? edges.filter((e) =>
          mentioned.some((n) => e.caller === n.id || e.callee === n.id)
        )
      : [];

  const allEdges = [...new Map(
    [...topEdges, ...neighborEdges].map((e) => [`${e.caller}->${e.callee}`, e])
  ).values()];

  const edgeLines = allEdges
    .slice(0, MAX_EDGES)
    .map((e) => `${e.caller} → ${e.callee}`);

  const lines = [
    "<!-- serpentine-graph-context -->",
    "## Codebase graph (auto-generated by serpentine)",
  ];
  if (topModules.length) lines.push(`Modules: ${topModules.join(", ")}`);
  if (edgeLines.length) lines.push(`Key calls:\n${edgeLines.map((l) => `  ${l}`).join("\n")}`);
  lines.push("<!-- /serpentine-graph-context -->");

  return lines.join("\n");
}

let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => (input += chunk));
process.stdin.on("end", () => {
  try {
    const { prompt = "" } = JSON.parse(input);
    const graph = loadGraph();
    if (!graph) process.exit(0);
    const summary = buildSummary(graph, prompt);
    if (Buffer.byteLength(summary) <= MAX_OUTPUT_BYTES) {
      process.stdout.write(summary + "\n");
    }
  } catch {
    // Never block the prompt
  }
  process.exit(0);
});

// Safety timeout — never block the prompt
setTimeout(() => process.exit(0), 3000);
